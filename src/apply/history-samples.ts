import { accessSync, constants } from "node:fs";
import { basename, dirname, extname } from "node:path";
import { inspectScanPath, type ApplyRepo } from "./catalog";

const sourceExtensions = new Set([
  ".c", ".cc", ".clj", ".cpp", ".cs", ".dart", ".ex", ".exs", ".fs", ".go", ".h", ".hpp", ".hs", ".java",
  ".js", ".jsx", ".kt", ".kts", ".lua", ".m", ".cjs", ".mjs", ".php", ".py", ".rb", ".rs", ".scala", ".sh",
  ".sql", ".svelte", ".swift", ".ts", ".cts", ".mts", ".tsx", ".vue", ".zig",
]);
const nonBusinessDirs = new Set([
  "__generated__", "__mocks__", "__snapshots__", "__tests__", "docs", "documentation", "doc", "e2e", "fixtures",
  "gen", "generated", "migrate", "migration", "migrations", "spec", "specs", "test", "tests", "testdata", "test-fixtures",
]);
const configTools = new Set([
  "astro", "babel", "biome", "commitlint", "cypress", "drizzle", "eslint", "jest", "lint-staged", "next", "nuxt",
  "playwright", "postcss", "prettier", "rollup", "rspack", "svelte", "tailwind", "tsup", "vite", "vitest", "webpack",
]);
const sourceRoots = new Set(["app", "cmd", "internal", "lib", "pkg", "source", "src"]);
const sampleLimit = 5;

export function isBusinessSource(path: string) {
  const filename = basename(path);
  const lower = filename.toLowerCase();
  const configTool = /^([a-z-]+)\.config\./.exec(lower)?.[1];
  return sourceExtensions.has(extname(lower)) &&
    !(configTool && configTools.has(configTool)) && !/^\.(?:babel|eslint|prettier)rc\./.test(lower) &&
    !dirname(path).split("/").some(segment => nonBusinessDirs.has(segment.toLowerCase())) &&
    !/(?:^|[._-])(?:tests?|spec|generated|gen|autogenerated)(?:[._-]|$)/.test(lower) &&
    !/(?:Test|Tests|IT|Spec)\.(?:java|kt|cs|scala|swift)$/.test(filename) &&
    !/\.(?:(?:pb|g)\.[a-z]+|pb\.(?:[^.]+\.)+go|d\.[cm]?ts|min\.js|designer\.cs)$/.test(lower) &&
    !/^(?:openapi\.|zz_generated_)/.test(lower) && !/^migrat(?:e|ion)[._-].*\.sql$/.test(lower);
}

function sampleModule(path: string, packages: Set<string>) {
  const directory = dirname(path);
  for (let parent = directory; parent !== "."; parent = dirname(parent)) {
    if (packages.has(parent)) return parent;
  }
  const parts = directory.split("/");
  const root = parts.findIndex(part => sourceRoots.has(part.toLowerCase()));
  return root < 0 ? parts[0] : parts.slice(0, root + 2).join("/");
}

function isReadableSample(repo: ApplyRepo, path: string) {
  try {
    const inspected = inspectScanPath(repo, path);
    if (!inspected.stat?.isFile() || !(inspected.stat.mode & 0o444)) return false;
    accessSync(inspected.path, constants.R_OK);
    return true;
  } catch { return false; }
}

export function pickStyleSamples(repo: ApplyRepo, ranked: [string, number][], packageDirs: string[]) {
  const packages = new Set(packageDirs);
  const represented = new Set<string>();
  const samples: { path: string; count: number }[] = [];
  const extras: { path: string; count: number }[] = [];
  for (const [path, count] of ranked) {
    if (!isBusinessSource(path)) continue;
    const module = sampleModule(path, packages);
    const repeated = represented.has(module);
    if (repeated && extras.length >= sampleLimit - samples.length) continue;
    if (!isReadableSample(repo, path)) continue;
    if (repeated) extras.push({ path, count });
    else {
      represented.add(module);
      samples.push({ path, count });
      if (samples.length === sampleLimit) break;
    }
  }
  return samples.concat(extras.slice(0, sampleLimit - samples.length));
}
